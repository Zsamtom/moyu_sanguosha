export function createPokemonCards(): SplendorCard[] {
  return POKEMON_DEFINITIONS.map(
    ([name, level, points, values, bonus, evolutionOf, evolutionValues], index) => ({
      id: `pokemon-${String(level)}-${index + 1}`,
      name,
      level,
      points,
      cost: compactCost(POKEMON_COLORS, values),
      bonus,
      bonusCount: level === "rare" || level === "legendary" ? 2 : 1,
      ...(evolutionOf ? { evolutionOf } : {}),
      ...(evolutionValues
        ? { evolutionReq: compactCost(POKEMON_COLORS, evolutionValues) }
        : {}),
    }),
  );
}
