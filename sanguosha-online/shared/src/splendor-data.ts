function compactCost(
  colors: readonly SplendorColor[],
  values: readonly number[],
): SplendorResourceMap {
  const result: SplendorResourceMap = {};
  colors.forEach((color, index) => {
    const value = values[index] ?? 0;
    if (value > 0) result[color] = value;
  });
  return result;
}

