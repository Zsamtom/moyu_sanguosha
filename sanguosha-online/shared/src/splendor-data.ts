export function createClassicCards(): SplendorCard[] {
  return CLASSIC_DEFINITIONS.map(([level, serial, points, bonus, cost]) => ({
    id: `classic-${level}-${serial}`,
    name: `${level}级${bonus}发展卡${serial}`,
    level,
    points,
    cost: compactCost(CLASSIC_COLORS, cost),
    bonus,
    bonusCount: 1,
  }));
}

